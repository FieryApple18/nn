using System;
using System.Collections.Generic;
using System.Linq;
using Sungero.Core;
using Sungero.CoreEntities;
using DirRX.NNCommons.HRSimpleDocument;

namespace DirRX.NNCommons.Shared
{
  partial class HRSimpleDocumentFunctions
  {
    /// <summary>
    /// Получить автоматически сформированное имя документа.
    /// </summary>
    /// <returns>Имя документа.</returns>
    [Public]
    public override string GetGeneratedDocumentName()
    {
      var name = string.Empty;
      using (TenantInfo.Culture.SwitchTo())
      {
        if (!string.IsNullOrWhiteSpace(_obj.DocumentKind.ToString()))
          name += _obj.DocumentKind;
        
        if (_obj.EmployeeDirRX != null)
          name += string.Format(" {0}", _obj.EmployeeDirRX.ToString());
        
        if (_obj.RegistrationDate != null)
          name += Sungero.Docflow.OfficialDocuments.Resources.DateFrom + _obj.RegistrationDate.Value.ToString("d");
      }
      
      return string.IsNullOrEmpty(name) ? GetAutogeneratedName() : name;
    }
    
    /// <summary>
    /// Получить подсказку для имени документа.
    /// </summary>
    /// <returns>Текст подсказки.</returns>
    public override string GetAutogeneratedName()
    {
      return base.GetAutogeneratedName();
    }
    
    public override void SetRequiredProperties()
    {
      base.SetRequiredProperties();
      _obj.State.Properties.Name.IsEnabled = false;
    }
  }
}