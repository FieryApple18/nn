using System;
using System.Collections.Generic;
using System.Linq;
using Sungero.Core;
using Sungero.CoreEntities;
using DirRX.NNCommons.DocumentsVisabilityLimitation;
using DirRX.OverrideSolution;

namespace DirRX.NNCommons.Shared
{
  partial class DocumentsVisabilityLimitationFunctions
  {

    /// <summary>
    /// Пороверить наличие дублей ограничения видимости документов в БД.
    /// </summary>
    /// <returns>Результат проверки. True - если дубли найдены, False - если дубли не найдены. </returns>
    [Public]
    public virtual bool HaveDuplicates()
    {
      return Functions.DocumentsVisabilityLimitation.Remote.GetDuplicates(_obj).Any();
    }

    /// <summary>
    /// Заполнить имя документа.
    /// </summary>
    [Public]
    public virtual void FillName()
    {
      var parts = new List<string> ();
      if (_obj.Role != null)
        parts.Add(_obj.Role.Name);
      if (_obj.BusinessUnit != null)
        parts.Add(_obj.BusinessUnit.Name);
      if (_obj.PersonnelSection != null)
        parts.Add(_obj.PersonnelSection.Name);
      
      var name = string.Join(". ", parts);
      
      _obj.Name = string.IsNullOrEmpty(name)? DirRX.NNCommons.DocumentsVisabilityLimitations.Resources.NameAutoGeneratedText : name;
    }
    
    
    /// <summary>
    /// Добавить сотрудников в табличную часть.
    /// </summary>
    /// <param name="employees">Список сотрудников.</param>
    [Public]
    public virtual void AddEmployees(List<IEmployee> employees)
    {
      var notAddedEmployees = employees.Where(x => !_obj.Employees.Any(e => Employees.Equals(e.Employee, x)));
      foreach (var employee in notAddedEmployees)
        _obj.Employees.AddNew().Employee = employee;
    }

  }
}