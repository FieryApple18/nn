using System;
using System.Collections.Generic;
using System.Linq;
using Sungero.Core;
using Sungero.CoreEntities;
using DirRX.NNOtherProcesses.LrdPaymentTypeSetting;

namespace DirRX.NNOtherProcesses.Shared
{
  partial class LrdPaymentTypeSettingFunctions
  {

    /// <summary>
    /// Заполнить имя настройки типа выплаты.
    /// </summary>
    public void FillName()
    {
      if (_obj.PaymentType == null || _obj.BusinessUnit == null)
      {
        _obj.Name = Constants.LrdPaymentTypeSetting.AutoGeneratedName;
        return;
      }
      
      _obj.Name = string.Format("{0}. {1}", _obj.PaymentType.Name, _obj.BusinessUnit.Name);
    }

    /// <summary>
    /// Установить доступность свойств.
    /// </summary>
    public void SetRequiredProperties()
    {
      _obj.State.Properties.PaymentAmount.IsRequired = _obj.FixedPayment == true;
    }

  }
}