using System;
using System.Collections.Generic;
using System.Linq;
using Sungero.Core;
using Sungero.CoreEntities;
using DirRX.OverrideSolution.DocRelatedToWorkBase;

namespace DirRX.OverrideSolution.Shared
{
  partial class DocRelatedToWorkBaseFunctions
  {

    /// <summary>
    /// Установить обязательность свойств в зависимости от заполнености данных.
    /// </summary>
    public override void SetRequiredProperties()
    {
      base.SetRequiredProperties();
      
      _obj.State.Properties.Subject.IsRequired = false;
    }

    /// <summary>
    /// Получить автоматически сформированное имя документа.
    /// </summary>
    /// <returns>Имя документа.</returns>
    [Public]
    public override string GetGeneratedDocumentName()
    {
      // HACK Seleznyov_DV Функция дублирует коробочную логику, добавляя возможность переопределить подсказку для имени через функцию GetAutogeneratedName().
      var documentKind = _obj.DocumentKind;
      var name = string.Empty;
      
      // Имя в формате: <Вид документа> №<номер> от <дата> "<содержание>".
      using (TenantInfo.Culture.SwitchTo())
      {
        if (!string.IsNullOrWhiteSpace(_obj.RegistrationNumber))
          name += OfficialDocuments.Resources.Number + _obj.RegistrationNumber;
        
        if (_obj.RegistrationDate != null)
          name += OfficialDocuments.Resources.DateFrom + _obj.RegistrationDate.Value.ToString("d");
        
        // HACK Toropov_AI При программном создании версии не из шаблона, в _obj.Subject записывается _obj.Name, что приводит к задвоению имени.
        if (!string.IsNullOrWhiteSpace(_obj.Subject) && _obj.Name != _obj.Subject)
          name += " \"" + _obj.Subject + "\"";
      }
      
      if (string.IsNullOrWhiteSpace(name))
      {
        if (_obj.VerificationState == null)
          name = GetAutogeneratedName();
        else
          name = _obj.DocumentKind.ShortName;
      }
      else if (documentKind != null)
      {
        name = documentKind.ShortName + name;
      }
      
      name = Sungero.Docflow.PublicFunctions.Module.TrimSpecialSymbols(name);
      
      return Sungero.Docflow.PublicFunctions.OfficialDocument.AddClosingQuote(name, _obj);
    }

    /// <summary>
    /// Получить подсказку для имени документа.
    /// </summary>
    /// <returns>Текст подсказки.</returns>
    public virtual string GetAutogeneratedName()
    {
      return Sungero.Docflow.Resources.DocumentNameAutotext;
    }

  }
}