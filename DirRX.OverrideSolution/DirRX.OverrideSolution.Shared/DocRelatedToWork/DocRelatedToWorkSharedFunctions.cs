using System;
using System.Collections.Generic;
using System.Linq;
using Sungero.Core;
using Sungero.CoreEntities;
using DirRX.OverrideSolution.DocRelatedToWork;

namespace DirRX.OverrideSolution.Shared
{
  partial class DocRelatedToWorkFunctions
  {

    /// <summary>
    /// Заполнить имя документа.
    /// </summary>
    [Public]
    public override void FillName()
    {
      var documentKind = _obj.DocumentKind;
      if (documentKind == null || !documentKind.GenerateDocumentName.Value)
        return;
      
      var additionalAgreement = Sungero.Docflow.PublicFunctions.DocumentKind.Remote
        .GetNativeDocumentKindRemote(NNOtherProcesses.PublicConstants.Module.DocumentKind.AdditionalAgreementKind);
      
      // Имя формируем только для ДС к трудовому договору.
      if (!DocumentKinds.Equals(additionalAgreement, documentKind))
      {
        base.FillName();
        return;
      }
      
      _obj.Name = GetGenerateAdditionalAgreementdDocumentName();
    }
    
    /// <summary>
    /// Получить автоматически сформированное имя документа для ДС к трудовому договору.
    /// </summary>
    /// <returns>Имя документа.</returns>
    [Public]
    public string GetGenerateAdditionalAgreementdDocumentName()
    {
      var documentKind = _obj.DocumentKind;
      var name = string.Empty;
      
      /* Имя в формате:
        <Вид документа> <ФИО> от <дата> (Табельный номер).
       */
      using (TenantInfo.Culture.SwitchTo())
      {
        if (_obj.EmployeeDirRX != null)
          name += string.Format(" {0}", Sungero.Company.PublicFunctions.Employee.GetShortName(_obj.EmployeeDirRX, DeclensionCase.Genitive, false));
        
        if (_obj.RegistrationDate != null)
          name += Sungero.Docflow.OfficialDocuments.Resources.DateFrom + _obj.RegistrationDate.Value.ToString("dd.MM.yyyy");
        
        if (_obj.EmployeeDirRX != null)
          name += string.Format(" ({0})", _obj.EmployeeDirRX.PersonnelNumber);
      }
      
      if (string.IsNullOrWhiteSpace(name))
      {
        if (_obj.VerificationState == null)
          name = GetAutogeneratedName();
        else
          name = _obj.DocumentKind.ShortName;
      }
      else if (documentKind != null)
      {
        name = documentKind.ShortName + name;
      }
      
      name = Sungero.Docflow.PublicFunctions.Module.TrimSpecialSymbols(name);
      return Sungero.Docflow.PublicFunctions.OfficialDocument.AddClosingQuote(name, _obj);
    }
  }
}